-- One naming scheme in the database: lower snake_case (0.4.0; DB-49, decided
-- by the owner on 16 October 2026). Every column, enum type, index and
-- constraint whose name was built from a camelCase field is renamed in place:
-- RENAME only, never a drop and an add, so no row moves and no value changes.
-- The Prisma client keeps its field names: schema.prisma maps each field and
-- enum to its new name (@map, @@map). Table names were already snake_case.
--
-- PostgreSQL 18 names every NOT NULL constraint after its column and keeps
-- that name when the column is renamed, so those are renamed too. The new
-- names are the ones a fresh database built from schema.prisma gets.

