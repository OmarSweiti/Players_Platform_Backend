-- Row-level security on every tenant-owned table; tenant ids immutable (0.4.5;
-- SYS-TEN-005, BR-RULE-01, SR-ACL-001; ADR-0004). The database itself keeps
-- each tenant's rows apart: the runtime role sees and writes only the rows of
-- the tenant its transaction names in app.tenant_id (withTenantTransaction,
-- 0.4.3), and with no tenant named it sees and writes nothing.
--
-- Each tenant-owned table gets, from src/infrastructure/prisma/model-classification.ts
-- through scripts/generate-rls.ts:
--   * ENABLE and FORCE ROW LEVEL SECURITY. FORCE holds the tables' owner to the
--     policies too, so no identity reads or writes a row by owning the table.
--   * <table>_tenant, the runtime role's one policy, for reads and writes.
--   * <table>_owner_reads: the owner reads every tenant's rows and writes none.
--     The migrator acts as the owner, so a preflight (just preflight) and a
--     data migration see the whole table, and the tenant_directory view reads
--     through it. A data migration that must write lifts FORCE on its table
--     inside its own transaction and restores it before it ends; the catalog
--     test (test/db/rls.integration-spec.ts) fails a table left without it.
--   * <table>_tenant_immutable: no UPDATE moves a row to another tenant.
-- The tenants table is held the same way by its id: a tenant sees and writes its
-- own row only. Reference data (permissions, the default role matrix) is
-- read-only to the runtime role.
--
-- Prisma runs this file as one transaction. The tables hold only synthetic data
-- (ADR-0021), so the locks are brief; one not granted within 5 s fails the
-- migration rather than queueing every request behind it.
SET LOCAL lock_timeout = '5s';

-- The trigger every tenant-owned table shares. Its argument names the column;
-- the message names the table and the column, never a value.
CREATE FUNCTION refuse_tenant_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '%.% cannot change: a row stays with its tenant', TG_TABLE_NAME, TG_ARGV[0]
    USING ERRCODE = 'integrity_constraint_violation';
END
$$;
REVOKE ALL ON FUNCTION refuse_tenant_change() FROM PUBLIC;

-- Generated by scripts/generate-rls.ts, every classified model, in the schema's order.
-- tenants: each tenant sees and writes its own row.
ALTER TABLE tenants ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenants FORCE ROW LEVEL SECURITY;
CREATE POLICY tenants_tenant ON tenants FOR ALL TO sadara_app
  USING (id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);
CREATE POLICY tenants_owner_reads ON tenants FOR SELECT TO sadara_owner USING (true);
CREATE TRIGGER tenants_tenant_immutable BEFORE UPDATE ON tenants
  FOR EACH ROW WHEN (OLD.id IS DISTINCT FROM NEW.id)
  EXECUTE FUNCTION refuse_tenant_change('id');

