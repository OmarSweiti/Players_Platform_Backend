-- Before anyone signs in, the tenant comes from the host (0.5.2), and jobs find
-- their tenants (0.7.6): both read this view, the routing columns and nothing
-- else. It reads tenants with its owner's rights, through tenants_owner_reads,
-- so the runtime role sees every tenant here and only its own row in tenants.
-- The registry role (0.7.6) is granted it when it exists.
CREATE VIEW tenant_directory AS
  SELECT id, slug, domain, is_active FROM tenants;
REVOKE ALL ON tenant_directory FROM sadara_app;
GRANT SELECT ON tenant_directory TO sadara_app;

-- The migration history is the migrator's: the runtime role neither reads it
-- nor records a migration as applied.
