-- Money: NUMERIC(19,4) with currency rules (0.4.7; ADR-0006, OPEN-09, DB-14).
-- Every money column becomes NUMERIC(19,4), which holds every currency's
-- decimals (JOD has three; the old columns kept two). A currency is a code of
-- currency_definitions: every ISO 4217 code with defined minor units, as the
-- list published 2026-09-17 gives them, all enabled by the owner's decision
-- (29 September 2026). An enrollment's payment records its own currency.
--
-- Widening the scale loses nothing: every stored amount keeps its value. An
-- existing payment whose currency was never recorded stops the migration: it
-- is not guessed from the programme (just preflight lists such rows as
-- money_currency_unknown).
--
-- Prisma runs this file as one transaction. The tables hold only synthetic data
-- (ADR-0021), so the rewrites are brief; a lock not granted within 5 s fails the
-- migration rather than queueing every request behind it.
SET LOCAL lock_timeout = '5s';

-- The currencies: src/common/money/iso-4217.ts is the list, and
-- test/db/money.integration-spec.ts holds this table to it.
CREATE TABLE currency_definitions (
  code CHAR(3) NOT NULL,
  minor_unit_exponent SMALLINT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT currency_definitions_pkey PRIMARY KEY (code),
  CONSTRAINT currency_definitions_code_check CHECK (code ~ '^[A-Z]{3}$'),
  CONSTRAINT currency_definitions_minor_unit_exponent_check CHECK (minor_unit_exponent BETWEEN 0 AND 4)
);

