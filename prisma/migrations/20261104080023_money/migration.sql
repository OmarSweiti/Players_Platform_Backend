-- Money columns: the same values, every currency's decimals.
ALTER TABLE contracts
  ALTER COLUMN salary_amount TYPE NUMERIC(19, 4),
  ALTER COLUMN signing_fee TYPE NUMERIC(19, 4),
  ALTER COLUMN salary_currency DROP DEFAULT,
  ALTER COLUMN salary_currency TYPE CHAR(3) USING salary_currency::text,
  ALTER COLUMN salary_currency SET DEFAULT 'JOD',
  ADD CONSTRAINT contracts_salary_currency_fkey FOREIGN KEY (salary_currency)
    REFERENCES currency_definitions (code) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE trainings
  ALTER COLUMN price TYPE NUMERIC(19, 4),
  ALTER COLUMN currency DROP DEFAULT,
  ALTER COLUMN currency TYPE CHAR(3) USING currency::text,
  ALTER COLUMN currency SET DEFAULT 'JOD',
  ADD CONSTRAINT trainings_currency_fkey FOREIGN KEY (currency)
    REFERENCES currency_definitions (code) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- A payment carries its own currency, whatever the programme's, and has one
-- whenever it has an amount.
ALTER TABLE enrollments
  ALTER COLUMN paid_amount TYPE NUMERIC(19, 4),
  ADD COLUMN paid_currency CHAR(3),
  ADD CONSTRAINT enrollments_paid_currency_fkey FOREIGN KEY (paid_currency)
    REFERENCES currency_definitions (code) ON DELETE RESTRICT ON UPDATE RESTRICT,
  ADD CONSTRAINT enrollments_paid_currency_check CHECK (paid_amount IS NULL OR paid_currency IS NOT NULL);

-- The four-value enum the currency columns used is gone.
DROP TYPE currency;
